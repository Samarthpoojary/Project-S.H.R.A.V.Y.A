corrupt_files = 0
for fname in mixed_files:
    fpath = os.path.join(mixed_dir, fname)
    audio, sr = sf.read(fpath)

    if np.isnan(audio).any() or np.isinf(audio).any():
        print(f"Corrupt values found in: {fname}")
        corrupt_files += 1

